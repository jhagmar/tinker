//! Emit `tinker-http.js` (JSDoc + `fetch` helpers).

use crate::http::{ErrorCode, HTTP_ROUTES, LanguageId, Listener};

/// JavaScript module text for `generated/tinker-http.js`.
#[must_use]
pub fn javascript_module() -> String {
    let mut out = String::new();
    out.push_str(HEADER);
    out.push_str(TYPEDEFS);
    out.push_str(&error_codes_js());
    out.push_str(&language_ids_js());
    out.push_str(&routes_js());
    out.push_str(HELPERS);
    out
}

fn error_codes_js() -> String {
    let mut s = String::from("export const errorCodes = [\n");
    for code in [
        ErrorCode::Full,
        ErrorCode::UnavailableLanguage,
        ErrorCode::LanguageMismatch,
        ErrorCode::UnknownProblem,
        ErrorCode::BadToken,
        ErrorCode::Denied,
        ErrorCode::Expired,
        ErrorCode::StartFailed,
        ErrorCode::BadRequest,
    ] {
        s.push_str("  '");
        s.push_str(code.as_str());
        s.push_str("',\n");
    }
    s.push_str("];\n\n");
    s
}

fn language_ids_js() -> String {
    let mut s = String::from("export const languageIds = [\n");
    for id in LanguageId::all() {
        s.push_str("  '");
        s.push_str(id.as_str());
        s.push_str("',\n");
    }
    s.push_str("];\n\n");
    s
}

fn routes_js() -> String {
    let mut s = String::from("export const httpRoutes = [\n");
    for r in HTTP_ROUTES {
        let listener = match r.listener {
            Listener::Public => "public",
            Listener::Admin => "admin",
        };
        s.push_str("  { name: '");
        s.push_str(r.name);
        s.push_str("', listener: '");
        s.push_str(listener);
        s.push_str("', method: '");
        s.push_str(r.method);
        s.push_str("', path: '");
        s.push_str(r.path);
        s.push_str("' },\n");
    }
    s.push_str("];\n\n");
    s
}

