#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn module_lists_stop_exports() {
        let js = javascript_module();
        for name in ["apply", "approve", "languages", "problems", "login"] {
            assert!(js.contains(&format!("export function {name}(")), "{name}");
            assert!(js.contains(&format!("name: '{name}'")), "route {name}");
        }
        assert!(js.contains("Generated by `tinker codegen`"));
        assert!(js.contains("export const httpRoutes"));
        assert!(js.contains("export const errorCodes"));
        assert!(js.contains("export const languageIds"));
        assert!(js.contains("'python'"));
        assert!(js.contains("'full'"));
        assert!(js.contains("listener: 'public'"));
        assert!(js.contains("listener: 'admin'"));
        assert!(js.contains("joinUrl"));
        assert!(!js.contains("eval("));
    }
}
